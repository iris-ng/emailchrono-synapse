"""
Many-small-tools baseline for the comparison. Hand-written, not generated by Synapse.

Exposes every adapter in app.review.dedupe and app.review.chronology as its own
MCP tool, one to one, with the adapter's own docstring as the description. The
agent has to chain them itself and pass each result back in. The two
Synapse-composed servers (resolve_case_duplicates_server.py and
review_chronology_server.py) do that chaining inside one tool each.

Same approval gate as the composed tools: there is no tool that approves or
declines a plan; apply_* returns waiting_for_approval until a person approves
in emailchrono.

The only change from the adapters: the two list functions return
{"case_id", "pairs"/"cards"} instead of a bare list, so each result is one
JSON object.

Run:  python small_tools_server.py
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from mcp.server.fastmcp import FastMCP

from app.review import chronology, dedupe

mcp = FastMCP("emailchrono_small_tools")


def _doc(function) -> str:
    return " ".join((function.__doc__ or "").split())


# --- duplicates ------------------------------------------------------------


@mcp.tool(name="check_case_ready_for_duplicate_review", description=_doc(dedupe.check_case_ready_for_duplicate_review))
def check_case_ready_for_duplicate_review(case_id: int) -> dict:
    return dedupe.check_case_ready_for_duplicate_review(case_id)


@mcp.tool(name="list_pending_duplicate_pairs", description=_doc(dedupe.list_pending_duplicate_pairs) + " Returned as {case_id, pairs}.")
def list_pending_duplicate_pairs(case_id: int) -> dict:
    return {"case_id": case_id, "pairs": dedupe.list_pending_duplicate_pairs(case_id)}


@mcp.tool(name="propose_duplicate_decision", description=_doc(dedupe.propose_duplicate_decision))
def propose_duplicate_decision(pair: Dict[str, Any]) -> dict:
    return dedupe.propose_duplicate_decision(pair)


@mcp.tool(name="save_duplicate_plan", description=_doc(dedupe.save_duplicate_plan))
def save_duplicate_plan(case_id: int, decisions: List[Dict[str, Any]], warnings: Optional[List[str]] = None) -> dict:
    return dedupe.save_duplicate_plan(case_id, decisions, warnings)


@mcp.tool(name="apply_duplicate_plan", description=_doc(dedupe.apply_duplicate_plan))
def apply_duplicate_plan(case_id: int, plan_id: str) -> dict:
    return dedupe.apply_duplicate_plan(case_id, plan_id)


# --- chronology ------------------------------------------------------------


@mcp.tool(name="check_case_ready_for_chronology_review", description=_doc(chronology.check_case_ready_for_chronology_review))
def check_case_ready_for_chronology_review(case_id: int) -> dict:
    return chronology.check_case_ready_for_chronology_review(case_id)


@mcp.tool(name="list_chronology_problem_cards", description=_doc(chronology.list_chronology_problem_cards) + " Returned as {case_id, cards}.")
def list_chronology_problem_cards(case_id: int) -> dict:
    return {"case_id": case_id, "cards": chronology.list_chronology_problem_cards(case_id)}


@mcp.tool(name="propose_splits", description=_doc(chronology.propose_splits))
def propose_splits(email_id: int) -> dict:
    return chronology.propose_splits(email_id)


@mcp.tool(name="propose_fields", description=_doc(chronology.propose_fields))
def propose_fields(email_id: int, split: Optional[Dict[str, Any]] = None) -> dict:
    return chronology.propose_fields(email_id, split)


@mcp.tool(name="save_chronology_plan", description=_doc(chronology.save_chronology_plan))
def save_chronology_plan(case_id: int, proposals: List[Dict[str, Any]], warnings: Optional[List[str]] = None) -> dict:
    return chronology.save_chronology_plan(case_id, proposals, warnings)


@mcp.tool(name="apply_chronology_plan", description=_doc(chronology.apply_chronology_plan))
def apply_chronology_plan(case_id: int, plan_id: str) -> dict:
    return chronology.apply_chronology_plan(case_id, plan_id)


if __name__ == "__main__":
    mcp.run()
