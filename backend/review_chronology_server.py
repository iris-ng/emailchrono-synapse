from __future__ import annotations

from mcp.server.fastmcp import FastMCP
from typing import Optional
from app.review.chronology import check_case_ready_for_chronology_review
from app.review.chronology import list_chronology_problem_cards
from app.review.chronology import propose_splits
from app.review.chronology import propose_fields
from app.review.chronology import save_chronology_plan
from app.review.chronology import apply_chronology_plan

mcp = FastMCP("review_chronology")


@mcp.tool(name="review_chronology", description="Review and manage email chronology plans for a case. Without plan_id, checks readiness, proposes splits for merged cards and fields for each problem card, saves a waiting plan, and returns the plan summary. With plan_id, applies the given plan (may still be waiting for approval). Never approves or declines plans.")
def review_chronology(case_id: int, plan_id: Optional[str] = None) -> dict:  # hand edit: "= None" (see README, Synapse-generated code)
    # Apply an existing chronology plan if plan_id is provided
    if plan_id is not None:
        try:
            result = apply_chronology_plan(case_id, plan_id)
        except Exception as e:
            return {"error": f"apply_chronology_plan failed: {e}", "case_id": case_id, "plan_id": plan_id}
        if not result:
            return {"error": "apply_chronology_plan returned no result", "case_id": case_id, "plan_id": plan_id}
        return result

    # Otherwise, build a new plan (no data changes beyond saving a waiting plan)
    try:
        readiness = check_case_ready_for_chronology_review(case_id)
    except Exception as e:
        return {"error": f"check_case_ready_for_chronology_review failed: {e}", "case_id": case_id}

    if not readiness:
        return {"error": "check_case_ready_for_chronology_review returned no result", "case_id": case_id}

    # If the case is not ready, return that result unchanged
    if not readiness.get("ok", False):
        return readiness

    warnings = readiness.get("warnings")

    try:
        cards = list_chronology_problem_cards(case_id)
    except Exception as e:
        return {"error": f"list_chronology_problem_cards failed: {e}", "case_id": case_id}

    if cards is None:
        return {"error": "list_chronology_problem_cards returned no result", "case_id": case_id}

    proposals = []
    for card in cards:
        email_id = card.get("email_id")
        if email_id is None:
            return {"error": "Problem card missing email_id", "case_id": case_id, "card": card}

        problems = card.get("problems") or []
        split = None

        if "merged" in problems:
            try:
                split = propose_splits(email_id)
            except Exception as e:
                return {"error": f"propose_splits failed for email_id {email_id}: {e}", "case_id": case_id}
            if not split:
                return {"error": f"propose_splits returned no result for email_id {email_id}", "case_id": case_id}

        try:
            fields = propose_fields(email_id, split)
        except Exception as e:
            return {"error": f"propose_fields failed for email_id {email_id}: {e}", "case_id": case_id}

        if not fields:
            return {"error": f"propose_fields returned no result for email_id {email_id}", "case_id": case_id}

        proposals.append(fields)

    try:
        save_result = save_chronology_plan(case_id, proposals, warnings)
    except Exception as e:
        return {"error": f"save_chronology_plan failed: {e}", "case_id": case_id}

    if not save_result:
        return {"error": "save_chronology_plan returned no result", "case_id": case_id}

    return save_result


